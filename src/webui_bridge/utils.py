import logging
import re
from typing import Optional


def setup_logging(level: int = logging.INFO) -> None:
    logging.basicConfig(
        level=level,
        format="%(asctime)s [%(levelname)s] %(name)s: %(message)s",
        datefmt="%H:%M:%S",
    )


def score_input_element(element_info: dict) -> float:
    score = 0.0
    tag = element_info.get("tag", "").lower()
    elem_type = element_info.get("type", "").lower()
    role = element_info.get("role", "").lower()
    placeholder = (element_info.get("placeholder") or "").lower()
    contenteditable = element_info.get("contenteditable", False)
    is_visible = element_info.get("visible", False)
    area = element_info.get("area", 0)

    if not is_visible:
        return 0.0

    if tag == "textarea":
        score += 3.0
    elif tag == "input" and elem_type in ("text", "search", ""):
        score += 2.0
    elif contenteditable:
        score += 2.5

    if role == "textbox":
        score += 1.5

    prompt_keywords = ["message", "prompt", "send", "ask", "chat", "type", "input"]
    for kw in prompt_keywords:
        if kw in placeholder:
            score += 1.0

    if area > 5000:
        score += 1.0
    elif area > 1000:
        score += 0.5

    return score


def score_send_button(element_info: dict, input_rect: Optional[dict] = None) -> float:
    score = 0.0
    tag = element_info.get("tag", "").lower()
    role = element_info.get("role", "").lower()
    text = (element_info.get("text") or "").lower()
    aria_label = (element_info.get("ariaLabel") or "").lower()
    is_visible = element_info.get("visible", False)
    has_click_listener = element_info.get("hasClickListener", False)
    svg_child = element_info.get("hasSvgChild", False)

    if not is_visible:
        return 0.0

    if tag == "button":
        score += 2.0
    elif role == "button":
        score += 1.5

    send_keywords = ["send", "submit", "go", "arrow", "paper", "plane", "chevron", ">"]
    for kw in send_keywords:
        if kw in text or kw in aria_label:
            score += 1.0

    if svg_child:
        score += 1.0

    if has_click_listener:
        score += 0.5

    if input_rect:
        rect = element_info.get("rect")
        if rect:
            dx = abs(rect["x"] - input_rect["x"])
            dy = abs(rect["y"] - input_rect["y"])
            distance = (dx ** 2 + dy ** 2) ** 0.5
            if distance < 100:
                score += 2.0
            elif distance < 300:
                score += 1.0

    return score


def score_chat_container(element_info: dict) -> float:
    score = 0.0
    tag = element_info.get("tag", "").lower()
    is_visible = element_info.get("visible", False)
    child_count = element_info.get("childCount", 0)
    has_scrollbar = element_info.get("hasScrollbar", False)
    text_density = element_info.get("textDensity", 0.0)
    mutation_count = element_info.get("mutationCount", 0)

    if not is_visible:
        return 0.0

    if child_count > 5:
        score += min(child_count * 0.2, 3.0)

    if has_scrollbar:
        score += 1.5

    if text_density > 0.3:
        score += 1.5

    if mutation_count > 0:
        score += min(mutation_count * 0.1, 2.0)

    return score


def classify_message_author(text: str, preceding_author: Optional[str] = None) -> str:
    if not text:
        return "assistant"

    lower = text.lower()
    user_indicators = [
        "you:", "user:", "human:", "me:", "sent by you",
    ]
    assistant_indicators = [
        "assistant:", "bot:", "model:", "ai:", "generated by",
    ]

    for indicator in user_indicators:
        if lower.startswith(indicator):
            return "user"
    for indicator in assistant_indicators:
        if lower.startswith(indicator):
            return "assistant"

    if preceding_author == "user":
        return "assistant"
    if preceding_author == "assistant":
        return "user"

    return "assistant"


def extract_code_blocks(text: str) -> list[dict]:
    """Extract code blocks from markdown text.

    Detects fenced (```), indented (4 spaces or tab), and inline (`` ` ``) code.

    Args:
        text: The markdown text to parse.

    Returns:
        A list of dictionaries, each containing:
        - language: str – language identifier for fenced blocks, otherwise empty.
        - code: str – the extracted code.
        - type: str – one of ``'fenced'``, ``'indented'``, ``'inline'``.
        - start_index: int – character index where the block starts in *text*.
        - end_index: int – character index where the block ends in *text*.
    """
    blocks: list[dict] = []

    # 1. Fenced code blocks
    fenced_pattern = re.compile(r"```(\w+)?\n(.*?)```", re.DOTALL)
    for match in fenced_pattern.finditer(text):
        blocks.append(
            {
                "language": match.group(1) or "",
                "code": match.group(2),
                "type": "fenced",
                "start_index": match.start(),
                "end_index": match.end(),
            }
        )

    # 2. Indented code blocks (4 spaces or tab at start of line, consecutive lines)
    indented_pattern = re.compile(r"(?:^(?:[ \t]{4,}|\t).+$\n?)+", re.MULTILINE)
    for match in indented_pattern.finditer(text):
        raw = match.group(0)
        dedented = re.sub(r"^(?:[ ]{4}|\t)", "", raw, flags=re.MULTILINE)
        blocks.append(
            {
                "language": "",
                "code": dedented,
                "type": "indented",
                "start_index": match.start(),
                "end_index": match.end(),
            }
        )

    # 3. Inline code (single backticks, not inside fenced blocks)
    # Pattern: backtick, content without newlines or backticks, backtick
    inline_pattern = re.compile(r"`([^`\n]+)`")
    for match in inline_pattern.finditer(text):
        # Skip if it falls inside any fenced block we already captured
        inside_fenced = any(
            b["type"] == "fenced" and b["start_index"] <= match.start() < b["end_index"]
            for b in blocks
        )
        if inside_fenced:
            continue
        blocks.append(
            {
                "language": "",
                "code": match.group(1),
                "type": "inline",
                "start_index": match.start(),
                "end_index": match.end(),
            }
        )

    # Sort by start_index so blocks appear in document order
    blocks.sort(key=lambda b: b["start_index"])
    return blocks


def extract_markdown_sections(text: str) -> list[dict]:
    """Split markdown text into structural sections.

    Identifies headers, lists, code blocks, and paragraphs.

    Args:
        text: The markdown text to split.

    Returns:
        A list of dictionaries, each containing:
        - type: str – one of ``'header'``, ``'list'``, ``'code'``, ``'paragraph'``.
        - content: str – the raw markdown content of the section.
        - level: int – header level (1–6) when *type* is ``'header'``, else ``None``.
    """
    sections: list[dict] = []
    lines = text.splitlines(keepends=True)
    i = 0

    while i < len(lines):
        line = lines[i]

        # Header
        header_match = re.match(r"^(#{1,6})\s+(.*)$", line)
        if header_match:
            level = len(header_match.group(1))
            sections.append(
                {
                    "type": "header",
                    "content": line.rstrip("\n"),
                    "level": level,
                }
            )
            i += 1
            continue

        # Fenced code block
        if line.startswith("```"):
            block = line
            i += 1
            while i < len(lines) and not lines[i].startswith("```"):
                block += lines[i]
                i += 1
            if i < len(lines):
                block += lines[i]
                i += 1
            sections.append({"type": "code", "content": block.rstrip("\n"), "level": None})
            continue

        # List item
        list_match = re.match(r"^(\s*)([-*+]|\d+\.)\s+(.*)$", line)
        if list_match:
            block = line
            indent = len(list_match.group(1))
            i += 1
            while i < len(lines):
                next_line = lines[i]
                if next_line.strip() == "":
                    block += next_line
                    i += 1
                    # Peek ahead – if the next non-empty line is also a list item, continue
                    if i < len(lines) and re.match(r"^(\s*)([-*+]|\d+\.)\s+", lines[i]):
                        continue
                    break
                # Another list item at the same or greater indent continues the block
                if re.match(r"^(\s*)([-*+]|\d+\.)\s+", next_line):
                    block += next_line
                    i += 1
                    continue
                # Continuation if indented more than the original item
                if next_line.startswith(" " * (indent + 2)) or not next_line.strip():
                    block += next_line
                    i += 1
                else:
                    break
            sections.append({"type": "list", "content": block.rstrip("\n"), "level": None})
            continue

        # Indented code block
        if line.startswith("    ") or line.startswith("\t"):
            block = line
            i += 1
            while i < len(lines) and (lines[i].startswith("    ") or lines[i].startswith("\t") or lines[i].strip() == ""):
                block += lines[i]
                i += 1
            sections.append({"type": "code", "content": block.rstrip("\n"), "level": None})
            continue

        # Paragraph (skip blank lines)
        if line.strip():
            block = line
            i += 1
            while i < len(lines):
                nxt = lines[i]
                if not nxt.strip():
                    break
                if nxt.startswith("#") or nxt.startswith("```") or nxt.startswith("    ") or nxt.startswith("\t"):
                    break
                if re.match(r"^(\s*)([-*+]|\d+\.)\s+", nxt):
                    break
                block += nxt
                i += 1
            sections.append({"type": "paragraph", "content": block.rstrip("\n"), "level": None})
            continue

        i += 1

    return sections


def strip_markdown(text: str) -> str:
    """Remove markdown syntax and return plain text.

    Strips headers, bold/italic, links, images, inline code backticks,
    fenced code block markers, list bullets, and blockquote markers.

    Args:
        text: The markdown text to clean.

    Returns:
        Plain text without markdown formatting.
    """
    # Remove fenced code block markers but keep content
    text = re.sub(r"```\w*\n", "", text)
    text = re.sub(r"```", "", text)

    # Remove headers
    text = re.sub(r"^#{1,6}\s+", "", text, flags=re.MULTILINE)

    # Remove bold / italic
    text = re.sub(r"\*\*\*(.*?)\*\*\*", r"\1", text)
    text = re.sub(r"\*\*(.*?)\*\*", r"\1", text)
    text = re.sub(r"__(.*?)__", r"\1", text)
    text = re.sub(r"\*(.*?)\*", r"\1", text)
    text = re.sub(r"_(.*?)_", r"\1", text)

    # Remove inline code backticks
    text = re.sub(r"`([^`]+)`", r"\1", text)

    # Remove links – keep the text part
    text = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", text)
    text = re.sub(r"\[([^\]]+)\]\[[^\]]*\]", r"\1", text)

    # Remove images – keep alt text
    text = re.sub(r"!\[([^\]]*)\]\([^)]+\)", r"\1", text)

    # Remove list bullets / numbers
    text = re.sub(r"^(\s*)([-*+]|\d+\.)\s+", r"\1", text, flags=re.MULTILINE)

    # Remove blockquote markers
    text = re.sub(r"^>\s?", "", text, flags=re.MULTILINE)

    # Remove horizontal rules
    text = re.sub(r"^-{3,}\s*$", "", text, flags=re.MULTILINE)
    text = re.sub(r"^\*{3,}\s*$", "", text, flags=re.MULTILINE)

    # Collapse multiple blank lines
    text = re.sub(r"\n{3,}", "\n\n", text)

    return text.strip()
